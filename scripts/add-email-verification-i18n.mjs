for (const [locale, additions] of Object.entries(COPY)) {
  const file = join(repoRoot, "shared", "i18n", "locales", locale, "auth.json");
  const raw = readFileSync(file, "utf8");
  const parsed = JSON.parse(raw);

  const missing = Object.entries(additions).filter(([key]) => !(key in parsed));
  if (missing.length === 0) {
    console.log(`${locale}: already up to date`);
    continue;
  }

  // Insert new entries before the closing brace, keeping the file's own
  // ordering convention (append) and exact 2-space indentation.
  const closingIndex = raw.lastIndexOf("}");
  const head = raw.slice(0, closingIndex).replace(/,\s*$/, "");
  const body = missing
    .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)}`)
    .join(",\n");

  writeFileSync(file, `${head},\n${body}\n}\n`, "utf8");

  const check = JSON.parse(readFileSync(file, "utf8"));
  console.log(`${locale}: added ${missing.length} keys (total ${Object.keys(check).length})`);
}
